/** Полноэкранный просмотр фото с масштабированием двумя пальцами. */
@Composable
fun ImageViewerDialog(path: String, onDismiss: () -> Unit) {
    var scale by remember { mutableFloatStateOf(1f) }
    var offset by remember { mutableStateOf(Offset.Zero) }
    Dialog(onDismissRequest = onDismiss, properties = DialogProperties(usePlatformDefaultWidth = false)) {
        Box(Modifier.fillMaxSize().background(Color.Black)) {
            AsyncImage(
                model = File(path),
                contentDescription = "Фото слайда",
                contentScale = ContentScale.Fit,
                modifier = Modifier
                    .fillMaxSize()
                    .pointerInput(Unit) {
                        detectTransformGestures { _, pan, zoom, _ ->
                            scale = (scale * zoom).coerceIn(1f, 6f)
                            offset = if (scale == 1f) Offset.Zero else offset + pan
                        }
                    }
                    .graphicsLayer(
                        scaleX = scale, scaleY = scale,
                        translationX = offset.x, translationY = offset.y,
                    ),
            )
            CloseButton(onDismiss)
        }
    }
}

/** Встроенный видеоплеер (Media3 ExoPlayer). */
@Composable
fun VideoPlayerDialog(path: String, onDismiss: () -> Unit) {
    val context = LocalContext.current
    val player = remember {
        ExoPlayer.Builder(context).build().apply {
            setMediaItem(MediaItem.fromUri(Uri.fromFile(File(path))))
            prepare()
            playWhenReady = true
        }
    }
    DisposableEffect(Unit) { onDispose { player.release() } }

    Dialog(onDismissRequest = onDismiss, properties = DialogProperties(usePlatformDefaultWidth = false)) {
        Box(Modifier.fillMaxSize().background(Color.Black)) {
            AndroidView(
                factory = { ctx -> PlayerView(ctx).apply { this.player = player } },
                modifier = Modifier.fillMaxSize(),
            )
            CloseButton(onDismiss)
        }
    }
}

@Composable
private fun androidx.compose.foundation.layout.BoxScope.CloseButton(onClick: () -> Unit) {
    IconButton(onClick = onClick, modifier = Modifier.align(Alignment.TopEnd).padding(16.dp)) {
        Icon(Icons.Filled.Close, "Закрыть", tint = Color.White)
    }
}
